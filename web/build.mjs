/* Unicollect front-end build (esbuild, no other tooling).

   node build.mjs           production build into the Python app + Pages site
   node build.mjs --watch   rebuild on change (pair with: node dev-server.mjs)

   Outputs
     app/static/        index.html  script.js  style.css   (Guard panel, served at /)
     app/chat_static/   index.html  script.js  style.css   (Unicollect Chat proxy UI)
     pages/             every site page prerendered with React (SSR) + assets/site.{js,css}
     pages/chat/        generated by scripts/sync_chat.py from app/static (pages mode)
*/
import * as esbuild from 'esbuild';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const SRC = path.join(HERE, 'src');
const OUT = {
  panel: path.join(ROOT, 'app', 'static'),
  chat: path.join(ROOT, 'app', 'chat_static'),
  pages: path.join(ROOT, 'pages'),
  ssr: path.join(HERE, '.ssr')
};
const WATCH = process.argv.includes('--watch');
const DEV = WATCH || process.argv.includes('--dev');

const common = {
  bundle: true,
  minify: !DEV,
  sourcemap: DEV ? 'inline' : false,
  legalComments: 'none',
  jsx: 'automatic',
  target: ['chrome92', 'firefox90', 'safari15'],
  loader: { '.json': 'json' },
  external: ['fonts/*'],
  define: { 'process.env.NODE_ENV': JSON.stringify(DEV ? 'development' : 'production') },
  logLevel: 'warning',
  charset: 'utf8'
};

const write = (file, text) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); };
const copy = (from, to) => { fs.mkdirSync(path.dirname(to), { recursive: true }); fs.copyFileSync(from, to); };
const hash = (...files) => { const h = createHash('sha1'); files.forEach(f => h.update(fs.readFileSync(f))); return h.digest('hex').slice(0, 10); };

async function bundle(entry, outdir, name, extra = {}) {
  const opts = { ...common, entryPoints: { [name]: path.join(SRC, entry) }, outdir, format: 'iife', platform: 'browser', ...extra };
  if (WATCH) { const ctx = await esbuild.context(opts); await ctx.watch(); return ctx; }
  const r = await esbuild.build(opts);
  const css = path.join(outdir, name + '.css');
  if (name === 'script' && fs.existsSync(css)) fs.renameSync(css, path.join(outdir, 'style.css'));
  return r;
}

/* ---------------- HTML shells ---------------- */
import { THEME_BOOT_SRC, FAVICON } from './shell.mjs';

const head = ({ title, desc, prefix, css, extra = '' }) => `<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>${title}</title>${desc ? `\n<meta name="description" content="${desc}">` : ''}
<meta name="color-scheme" content="dark">
<meta name="theme-color" content="#0d0916">
<link rel="preload" href="${prefix}fonts/Vazirmatn.woff2?v=1" as="font" type="font/woff2" crossorigin>
<link rel="icon" type="image/svg+xml" href="${prefix}favicon.svg">
<link rel="stylesheet" href="${css}">${extra}
<script>${THEME_BOOT_SRC}</script>`;

